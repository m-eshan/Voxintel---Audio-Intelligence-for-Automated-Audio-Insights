from __future__ import annotations

import io
from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas

TEMPLATES_DIR = Path(__file__).resolve().parents[1] / "templates"


def render_mom_html(context: dict) -> str:
    from jinja2 import Environment, FileSystemLoader, select_autoescape

    env = Environment(
        loader=FileSystemLoader(str(TEMPLATES_DIR)),
        autoescape=select_autoescape(["html", "xml"]),
    )
    template = env.get_template("mom_report.html.j2")
    return template.render(**context)


def render_mom_pdf(context: dict) -> bytes:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    x = 0.7 * inch
    y = height - 0.7 * inch

    def write_line(text: str, font_name: str = "Helvetica", font_size: int = 10) -> None:
        nonlocal y
        if y < 0.8 * inch:
            pdf.showPage()
            y = height - 0.7 * inch
        pdf.setFont(font_name, font_size)
        pdf.drawString(x, y, text[:115])
        y -= 14

    pdf.setTitle(context.get("title", "VoxIntel Minutes of Meeting"))
    write_line(context.get("title", "VoxIntel Minutes of Meeting"), "Helvetica-Bold", 15)
    write_line(f"Generated by VoxIntel", "Helvetica", 9)
    write_line("")

    write_line("Summary", "Helvetica-Bold", 12)
    for line in _wrap_text(context.get("summary", ""), max_chars=110):
        write_line(line)

    write_line("")
    write_line("Participants", "Helvetica-Bold", 12)
    write_line(", ".join(context.get("participants", []) or ["Unknown"]))

    write_line("")
    write_line("Discussion Points", "Helvetica-Bold", 12)
    for item in context.get("discussion_points", []):
        for line in _wrap_text(f"- {item}", max_chars=110):
            write_line(line)

    write_line("")
    write_line("Decisions", "Helvetica-Bold", 12)
    for item in context.get("decisions", []):
        for line in _wrap_text(f"- {item}", max_chars=110):
            write_line(line)

    risks = context.get("risks", [])
    if risks:
        write_line("")
        write_line("Risks", "Helvetica-Bold", 12)
        for item in risks:
            for line in _wrap_text(f"- {item}", max_chars=110):
                write_line(line)

    write_line("")
    write_line("Action Items", "Helvetica-Bold", 12)
    for item in context.get("action_items", []):
        line = f"- {item.get('task', '')} | Owner: {item.get('owner', 'Unknown')} | Deadline: {item.get('deadline', 'Unknown')}"
        for wrapped in _wrap_text(line, max_chars=110):
            write_line(wrapped)

    pdf.save()
    buffer.seek(0)
    return buffer.read()


def _wrap_text(text: str, max_chars: int = 100) -> list[str]:
    if len(text) <= max_chars:
        return [text]
    words = text.split()
    lines: list[str] = []
    current: list[str] = []
    current_len = 0
    for word in words:
        if current and current_len + len(word) + 1 > max_chars:
            lines.append(" ".join(current))
            current = [word]
            current_len = len(word)
        else:
            current.append(word)
            current_len += len(word) + (1 if current_len else 0)
    if current:
        lines.append(" ".join(current))
    return lines
